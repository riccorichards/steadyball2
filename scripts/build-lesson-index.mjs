// Lists every lesson in lessons/ for the app, and stops with a clear message if one is broken.
// Runs before `npm run dev` and `npm run build`. Lessons play in file-name order (01-…, 02-…).
//
// To add a lesson: export it from Pitch Scenario Studio and save it here as NN-name.lesson.json.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { validateLesson, formatPath } from "@pss/player";

const dir = new URL("../lessons/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".lesson.json")).sort();

const ids = new Set();
const meta = [];
let broken = 0;
for (const f of files) {
  let raw;
  try {
    raw = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
  } catch (e) {
    console.error(`✗ lessons/${f}: not valid JSON (${e.message})`);
    broken++;
    continue;
  }
  const r = validateLesson(raw);
  if (!r.ok) {
    console.error(`✗ lessons/${f}:\n${r.issues.map((i) => `    ${formatPath(i.path) || "(lesson)"}: ${i.message}`).join("\n")}`);
    broken++;
    continue;
  }
  if (ids.has(r.value.id)) {
    console.error(`✗ lessons/${f}: id "${r.value.id}" is used by another lesson`);
    broken++;
  }
  ids.add(r.value.id);
  meta.push({ id: r.value.id, title_ka: r.value.meta.title.ka ?? r.value.meta.title.en ?? r.value.id, title_en: r.value.meta.title.en ?? r.value.meta.title.ka ?? r.value.id });
}
if (broken) {
  console.error(`\n${broken} lesson file(s) need fixing (open them in the Studio, fix, export again).`);
  process.exit(1);
}

const head = ["// GENERATED by scripts/build-lesson-index.mjs before dev/build. Do not edit:", "// add or remove .lesson.json files in this folder instead.", ""];
// index.ts: ids and titles only (safe for server pages, no lesson data).
writeFileSync(
  new URL("index.ts", dir),
  [
    ...head,
    "/** Lessons in play order: id and titles. */",
    `export const LESSON_META: { id: string; title_ka: string; title_en: string }[] = ${JSON.stringify(meta, null, 2)};`,
    "",
  ].join("\n"),
);
// files.ts: the lesson files themselves (for the player, in the browser).
writeFileSync(
  new URL("files.ts", dir),
  [
    ...head,
    ...files.map((f, i) => `import l${i} from "./${f}";`),
    "",
    "/** Lesson files in play order (raw JSON; lib/lessons.ts validates them). */",
    `export const LESSON_FILES: unknown[] = [${files.map((_, i) => `l${i}`).join(", ")}];`,
    "",
  ].join("\n"),
);
console.log(`✓ ${files.length} lesson(s)`);
